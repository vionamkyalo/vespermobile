import json
import os
import urllib.request

BASE = os.environ.get("VESPER_API", "https://relive-mummified-jovial.ngrok-free.dev/api")
OUT = "lib/features/forms/data/zone_seed.dart"


def call(path, body=None, token=None):
    headers = {"Content-Type": "application/json", "ngrok-skip-browser-warning": "true"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(
        BASE + path,
        data=json.dumps(body).encode() if body else None,
        headers=headers,
        method="POST" if body else "GET",
    )
    with urllib.request.urlopen(req) as resp:
        return json.load(resp)


def dart_str(s):
    return json.dumps(s).replace("$", "\\$")


def main():
    token = call("/auth/login", {
        "email": os.environ["VESPER_EMAIL"],
        "password": os.environ["VESPER_PASSWORD"],
    })["access_token"]
    zones = call("/zones?active_only=true", token=token)

    lines = [
        "// GENERATED by tool/generate_zone_seed.py. Do not edit by hand.",
        "import '../inspection_form_repository.dart';",
        "",
        "const kZoneSeed = <FormZone>[",
    ]
    for z in sorted(zones, key=lambda z: z["name"]):
        geo = z.get("boundary") or {}
        ring = []
        if geo.get("type") == "Polygon" and geo.get("coordinates"):
            ring = geo["coordinates"][0]
        pts = ", ".join(f"[{float(p[0])}, {float(p[1])}]" for p in ring)
        lines.append(
            f"  FormZone(id: {dart_str(z['zone_id'])}, "
            f"name: {dart_str(z['name'])}, boundary: [{pts}]),"
        )
    lines.append("];")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(zones)} zones to {OUT}")


if __name__ == "__main__":
    main()